// Rebuilds lib/field-data.ts from the ATHX team leaderboard: every mixed ATHX
// Lite pair's Strength score for one season. Run from athx-tracker/:
//
//   node scripts/pull-field.mjs 2026
//
// The leaderboard is an Inertia page, so each page of results sits in its
// data-page attribute as JSON. Filters are looked up by their labels rather
// than hard-coded ids, which the site could change.
import { writeFileSync } from "node:fs";

const BASE = "https://athxgames.com/team-leaderboards";
const year = process.argv[2] ?? "2026";
const OUT = new URL("../lib/field-data.ts", import.meta.url);

const ENTITIES = { "&quot;": '"', "&amp;": "&", "&#039;": "'", "&lt;": "<", "&gt;": ">" };
const unescape = (text) => text.replace(/&(?:quot|amp|#039|lt|gt);/g, (entity) => ENTITIES[entity]);
const pause = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

async function props(query) {
  const response = await fetch(`${BASE}?${new URLSearchParams(query)}`, {
    headers: { "User-Agent": "athx-tracker field refresh" },
  });
  if (!response.ok) throw new Error(`${BASE} answered ${response.status}`);
  const raw = (await response.text()).match(/data-page="([^"]+)"/)?.[1];
  if (!raw) throw new Error("No leaderboard data on the page; the site has changed.");
  return JSON.parse(unescape(raw)).props;
}

const first = await props({ "filters[year]": year });
const option = (key, label) => {
  const value = first.filters.find((filter) => filter.key === key)
    ?.options.find((choice) => choice.label === label)?.value;
  if (!value) throw new Error(`No "${label}" under the leaderboard's ${key} filter.`);
  return value;
};
const query = {
  "filters[year]": year,
  "filters[gender]": option("gender", "Mixed"),
  "filters[event_category]": option("event_category", "ATHX Lite"),
};

const rows = [];
for (let page = 1, last = 1; page <= last; page += 1) {
  if (page > 1) await pause(800);
  const { results } = await props({ ...query, page });
  last = results.meta.last_page;
  rows.push(...results.data);
}

const strength = rows
  .map((row) => Number(/\(([\d.]+)KG\)/i.exec(row.Strength)?.[1]))
  .filter((kg) => kg > 0)
  .sort((a, b) => a - b);
if (strength.length !== rows.length) throw new Error("Some Strength scores did not read as kilograms.");
const events = new Set(rows.map((row) => row.event)).size;
const pulled = new Date().toISOString().slice(0, 10);

const lines = [];
for (let i = 0; i < strength.length; i += 16) lines.push(`    ${strength.slice(i, i + 16).join(", ")},`);
writeFileSync(
  OUT,
  `// Generated by scripts/pull-field.mjs from ${BASE}. Do not edit by hand.
export const FIELD_DATA: {
  season: number;
  pulled: string;
  events: number;
  /** Each pair's Strength score in kilograms, lowest first. */
  strength: readonly number[];
} = {
  season: ${Number(year)},
  pulled: "${pulled}",
  events: ${events},
  strength: [
${lines.join("\n")}
  ],
};
`,
);
console.log(`${strength.length} mixed Lite pairs from ${events} events in ${year} -> lib/field-data.ts`);
